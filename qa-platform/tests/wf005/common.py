def make_workcenter(rpc, label: str) -> int:
    return rpc.create("mrp.workcenter", {"name": tag(label)})


def make_operation_type(rpc, label: str,
                        lines: list[tuple[str, int, int]]) -> int:
    """lines = [(operation_name, workcenter_id, sequence), ...]."""
    return rpc.create("mrp.operation.type", {
        "name": tag(label),
        "operation_type_line_ids": [
            (0, 0, {"name": name, "workcenter_id": wc, "sequence": seq})
            for name, wc, seq in lines],
    })


def operation_lines(rpc, op_type_id: int) -> list[dict]:
    return rpc.search_read(
        "mrp.operation.type.line",
        [("mrp_operation_type_id", "=", op_type_id)],
        ["name", "workcenter_id", "sequence"], order="sequence, id")


def make_product(rpc, label: str) -> int:
    values = {
        "name": tag(label),
        "default_code": f"{_TOKEN}-{label}",
        "type": "consu",
    }
    if rpc.field_exists("product.template", "is_storable"):
        values["is_storable"] = True
    else:
        values["type"] = "product"
    return rpc.create("product.product", with_categ(rpc, values))


def product_tmpl_of(rpc, product_id: int) -> int:
    return m2o_id(rpc.read("product.product", [product_id],
                           ["product_tmpl_id"])[0]["product_tmpl_id"])


def make_bom(rpc, finished_id: int, component_id: int,
             operations: list[tuple[str, int]] | None = None) -> int:
    """A BoM, optionally carrying core's own routing operations.

    ``operations`` exists for TC105: with no MO Operation Type set, core's
    BoM-driven routing must survive untouched, and that can only be observed
    on a BoM that actually has operations.
    """
    values = {
        "product_tmpl_id": product_tmpl_of(rpc, finished_id),
        "code": tag("BOM"),
        "product_qty": 1.0,
        "type": "normal",
        "bom_line_ids": [(0, 0, {"product_id": component_id, "product_qty": 1.0})],
    }
    if operations:
        values["operation_ids"] = [
            (0, 0, {"name": name, "workcenter_id": wc})
            for name, wc in operations]
    return rpc.create("mrp.bom", values)


_MO_SEQ = {"n": 0}


def make_mo(rpc, finished_id: int, bom_id: int, qty: float = 1.0,
            op_type_id: int | None = None, confirm: bool = False) -> int:
    # mrp.production.name carries a "Reference must be unique per Company!"
    # constraint, so several MOs inside one case need distinct names. A
    # per-process counter keeps them readable and still inside the marker.
    _MO_SEQ["n"] += 1
    values = {
        "product_id": finished_id,
        "product_tmpl_id": product_tmpl_of(rpc, finished_id),
        "bom_id": bom_id,
        "product_qty": qty,
        "name": tag(f"MO-{_MO_SEQ['n']:03d}"),
    }
    if op_type_id is not None:
        values["mrp_operation_type_id"] = op_type_id
    mo_id = rpc.create("mrp.production", values)
    if confirm:
        rpc.call("mrp.production", "action_confirm", [mo_id])
    return mo_id


def workorders(rpc, mo_id: int) -> list[dict]:
    """The MO's work orders in operation-type line order.

    Ordered by ``operation_type_line_sequence`` first — that is the order the
    workbook asserts — then by id so the ordering is total even for rows core
    generated, which carry sequence 0.
    """
    return rpc.search_read(
        "mrp.workorder", [("production_id", "=", mo_id)],
        ["name", "workcenter_id", "state", "mrp_operation_type_id",
         "mrp_operation_type_line_id", "operation_type_line_sequence"],
        order="operation_type_line_sequence, id")


def workorder_ids(rpc, mo_id: int) -> list[int]:
    return [w["id"] for w in workorders(rpc, mo_id)]


def still_exists(rpc, model: str, ids: list[int]) -> list[int]:
    """Which of `ids` still exist — TC102 step 9 asserts this is empty."""
    if not ids:
        return []
    return rpc.search(model, [("id", "in", ids)])
