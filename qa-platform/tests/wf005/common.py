def require_operation_types(ctx):
    """BLOCK unless dto_mrp contributed the operation-type layer."""
    rpc = ctx.adapter.rpc
    missing = [m for m in ("mrp.operation.type", "mrp.operation.type.line")
               if not rpc.model_exists(m)]
    missing += [f"mrp.production.{f}" for f in ("mrp_operation_type_id",)
                if not rpc.field_exists("mrp.production", f)]
    missing += [f"mrp.workorder.{f}" for f in
                ("mrp_operation_type_id", "mrp_operation_type_line_id",
                 "operation_type_line_sequence")
                if not rpc.field_exists("mrp.workorder", f)]
    if missing:
        ctx.blocked(
            f"dto_mrp is not contributing MO Operation Types to {ctx.env.key} "
            f"(db={ctx.env.db}) — missing: {', '.join(missing)}. Stage 3 must "
            f"be installed (tools/uat_cleanup.sh) first.")


